// ║   yolo_detector 等检测模块解码出候选框后经 NMS 去重再返回上层。                ║
// ║   坐标约定：一律归一化 [0,1]（除以帧宽高），与分辨率解耦，                      ║
// ║   预览/录像/截图任意尺寸的帧乘各自宽高即可复用同一份结果。                      ║
// ╚═══════════════════════════════════════════════════════════════════════════╝
// ★ NMS 头文件：Detection 去重接口声明
#ifndef NMS_H
#define NMS_H

#include <vector>

// ★ Detection：单个检测结果（NMS 的输入输出单元）。
//   用归一化坐标而非像素坐标：检测结果与显示尺寸解耦，
//   旋转/变焦后换算比例即可复用
struct Detection {
    float x, y, w, h;   // 归一化到 [0,1]（x/y=框左上角，w/h=框宽高，均除以帧宽/帧高）
    // 类别置信度：YOLOv8 解耦头下即该 anchor 的最大类别分数
    float score;
    // 类别索引：对应模型类别表下标（上层映射为鱼种名/颜色）
    int   label;
};

// ★ NMS：非极大值抑制。dets 就地按分数降序排序后贪心保留，返回去重结果；
//   iouThresh 为 IoU 抑制阈值；只在同类别框之间互相抑制（不同鱼种允许重叠共存）；
//   另含 IoM>0.80 的"包含抑制"补丁，压掉鱼群遮挡时的套娃框（详见 nms.cpp）
std::vector<Detection> NMS(std::vector<Detection> &dets, float iouThresh);

#endif // NMS_H